HARNESS = r'''
extends SceneTree
var failures := 0
func need(ok: bool, message: String):
    if not ok:
        failures += 1
        push_error(message)
func _initialize():
    call_deferred("run_checks")
func settle():
    await process_frame
    await process_frame
func run_checks():
    var scene = load("res://VolibearArt/scenes/volibear_energy.tscn")
    var counter = scene.instantiate()
    root.add_child(counter)
    await settle()
    var label = counter.get_node("Label")
    var ring = counter.get_node("Layers/RotationLayers/StormRing")
    var core = counter.get_node("Layers/Core")
    var emblem = counter.get_node("Layers/Emblem")
    need(ring.get("_has_value") and ring.get("_energy_value") == 3, "Real script binds full native-label-shaped value")
    var bright = core.get_theme_stylebox("panel").bg_color
    need(emblem.texture.resource_path.ends_with("energy_master.png"), "Charged emblem selected")
    label.text = "0/3"
    await settle()
    need(ring.get("_energy_value") == 0, "Actual script reads depletion")
    var dark = core.get_theme_stylebox("panel").bg_color
    need(bright.g > dark.g * 3 and bright.b > dark.b * 3, "Core changes visibly, not only the numeral")
    need(emblem.texture.resource_path.ends_with("big_energy_empty.png"), "Empty emblem selected")
    need(ring.get("_pulse") == 0.0, "No lingering charge pulse on empty")
    var phase = ring.get("_phase")
    await settle()
    need(ring.get("_phase") == phase, "Empty cosmetic phase stops")
    label.text = "[color=cyan]2/3[/color]"
    await settle()
    need(ring.get("_energy_value") == 2 and emblem.texture.resource_path.ends_with("energy_master.png"), "Refill restores charged visuals")
    counter.remove_child(label)
    label.free()
    label = Label.new()
    label.name = "Label"
    label.text = "1/3"
    counter.add_child(label)
    await settle()
    need(ring.get("_energy_value") == 1, "Replacement native Label rebinds without a stale pointer")
    label.text = "?"
    await settle()
    need(ring.get("_energy_value") == 1 and label.text == "?", "Unknown text is preserved, never rewritten or interpreted as zero")
    var late = scene.instantiate()
    var original = late.get_node("Label")
    late.remove_child(original)
    original.free()
    root.add_child(late)
    await settle()
    var late_label = Label.new()
    late_label.name = "Label"
    late_label.text = "0/3"
    late.add_child(late_label)
    await settle()
    var late_ring = late.get_node("Layers/RotationLayers/StormRing")
    need(late_ring.get("_has_value") and late_ring.get("_energy_value") == 0, "Late-created native Label binds")
    var cost = load("res://VolibearArt/ui/images/big_energy.png").get_image()
    var center = cost.get_pixel(37,37)
    var quiet := true
    for x in range(25,49):
        for y in range(22,52):
            if cost.get_pixel(x,y) != center:
                quiet = false
    need(quiet and center.a == 1.0, "Fee glyph safe rectangle is a single opaque color")
    var full_image = load("res://VolibearArt/ui/images/energy_master.png").get_image()
    var empty_image = load("res://VolibearArt/ui/images/big_energy_empty.png").get_image()
    full_image.resize(74,74,Image.INTERPOLATE_LANCZOS)
    var full_light := 0.0
    var empty_light := 0.0
    for x in range(74):
        for y in range(74):
            var f = full_image.get_pixel(x,y)
            var e = empty_image.get_pixel(x,y)
            full_light += f.get_luminance() * f.a
            empty_light += e.get_luminance() * e.a
    need(full_light > empty_light * 3.0, "Full/empty emblem luminance contrast exceeds 3x")
    counter.queue_free()
    late.queue_free()
    await process_frame
    if failures == 0:
        print("ENERGY_STATE_SCRIPT_PASS full-empty-refill late-and-replaced-label quiet-cost-center")
    quit(0 if failures == 0 else 1)
'''


class EnergyStates(unittest.TestCase):
    def test_manifest_hashes_and_original_inline_icon_are_preserved(self):
        manifest = json.loads((UI / 'manifest.json').read_text())
        javascript = (UI / 'manifest.js').read_text()
        self.assertEqual(json.loads(javascript.removeprefix('window.VOLIBEAR_UI=').strip().removesuffix(';')), manifest)
        for item in manifest['assets']:
            self.assertEqual(hashlib.sha256((UI / item['file']).read_bytes()).hexdigest(), item['sha256'], item['id'])
        # The original inline symbol is still generated by the unchanged energy(24).
        self.assertIn("save(energy(24),'text_energy.png'", (UI / 'scripts/build_ui.py').read_text())

    def test_energy_generator_preserves_frozen_inputs_and_reproduces_exact_pixels(self):
        python = (Path(sys.executable) if importlib.util.find_spec('PIL') is not None else
                  ROOT / '.local/build-python' / ('Scripts/python.exe' if os.name == 'nt' else 'bin/python'))
        if not python.is_file():
            self.skipTest('Project Pillow asset environment unavailable')
        with tempfile.TemporaryDirectory() as temporary:
            target = Path(temporary)
            (target / 'scripts').mkdir(); (target / 'images').mkdir()
            shutil.copyfile(UI / 'scripts/build_ui.py', target / 'scripts/build_ui.py')
            for name in ('manifest.json', 'manifest.js'):
                shutil.copyfile(UI / name, target / name)
            names = ('big_energy.png', 'energy_master.png', 'big_energy_empty.png', 'text_energy.png')
            for name in names:
                shutil.copyfile(UI / 'images' / name, target / 'images' / name)
            inline_before = (target / 'images/text_energy.png').read_bytes()
            before = json.loads((target / 'manifest.json').read_text())
            result = subprocess.run([str(python), '-B', str(target / 'scripts/build_ui.py'), '--energy-only'],
                                    capture_output=True, text=True, timeout=15)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            after = json.loads((target / 'manifest.json').read_text())
            changed_ids = {'big_energy', 'energy_master', 'big_energy_empty'}
            self.assertEqual([row for row in before['assets'] if row['id'] not in changed_ids],
                             [row for row in after['assets'] if row['id'] not in changed_ids])
            self.assertEqual(inline_before, (target / 'images/text_energy.png').read_bytes())
            self.assertEqual(set(p.name for p in (target / 'images').iterdir()), set(names))
            # Frozen source hashes are checked above; untouched inline PNG stays byte-exact.
            self.assertEqual((target / 'images/text_energy.png').read_bytes(), (UI / 'images/text_energy.png').read_bytes())
            # PNG compression can differ across Pillow/zlib builds. Decode using the
            # selected Pillow interpreter and require identical format, mode, size and
            # every RGBA pixel, without changing the approved files or their hashes.
            decode = '''import json, sys
from pathlib import Path
from PIL import Image
rows = []
for name in sys.argv[3:]:
    pair = []
    for directory in sys.argv[1:3]:
        with Image.open(Path(directory) / name) as image:
            pair.append([image.format, image.mode, image.size, image.convert('RGBA').tobytes().hex()])
    rows.append(pair)
print(json.dumps(rows))
'''
            decoded = subprocess.run([str(python), '-B', '-c', decode, str(target / 'images'),
                                      str(UI / 'images'), *names[:3]],
                                     capture_output=True, text=True, timeout=15)
            self.assertEqual(decoded.returncode, 0, decoded.stdout + decoded.stderr)
            rows = json.loads(decoded.stdout)
            self.assertEqual(len(rows), 3)
            for name, (generated, approved) in zip(names[:3], rows):
                self.assertEqual(generated[0], 'PNG', name)
                self.assertEqual(approved[0], 'PNG', name)
                self.assertEqual(generated, approved, name)

    def test_empty_draw_returns_before_all_charge_effects(self):
        script = (PRESENTATION / 'energy.gd').read_text()
        draw = script.split('func _draw() -> void:', 1)[1]
        empty, charged = draw.split('\n\tvar blue =', 1)
        self.assertIn('_energy_value <= 0', empty)
        self.assertIn('\n\t\treturn', empty)
        self.assertNotIn('draw_polyline', empty)
        self.assertNotIn('_pulse >', empty)
        self.assertIn('draw_polyline', charged)
        self.assertNotRegex(script, r'_label\.text\s*=(?!=)')

    def test_actual_gdscript_and_image_contrast_in_standalone_engine(self):
        runtime = fixture_runtime(self, 'godot', root=ROOT)
        with tempfile.TemporaryDirectory() as temporary:
            project = Path(temporary)
            scenes = project / 'VolibearArt/scenes'; scenes.mkdir(parents=True)
            images = project / 'VolibearArt/ui/images'; images.mkdir(parents=True)
            for name in ('energy.gd', 'volibear_energy.tscn'):
                shutil.copyfile(PRESENTATION / name, scenes / name)
            for name in ('energy_master.png', 'big_energy_empty.png', 'big_energy.png',
                         'energy_orb_charged.png', 'energy_orb_empty.png'):
                shutil.copyfile(UI / 'images' / name, images / name)
            env = runtime.isolated_environment(project / 'profile')
            (project / 'project.godot').write_text(
                'config_version=5\n[rendering]\nrenderer/rendering_method="gl_compatibility"\n'
                + isolated_tls_settings(project, env), encoding='utf-8')
            (project / 'verify.gd').write_text(HARNESS)
            env['GODOT_SILENCE_ROOT_WARNING'] = '1'
            for arguments in (['--editor', '--import', '--quit'], ['--script', 'res://verify.gd']):
                result = subprocess.run([str(runtime.godot), '--headless', '--path', str(project), *arguments],
                                        env=env, capture_output=True, text=True, encoding='utf-8', timeout=60)
                output = result.stdout + result.stderr
                self.assertEqual(result.returncode, 0, output)
                self.assertNotIn('SCRIPT ERROR:', output)
                errors = '\n'.join(line for line in output.splitlines() if 'ERROR:' in line or line.startswith('   at:'))
                self.assertEqual(errors, '', errors)
            self.assertIn('ENERGY_STATE_SCRIPT_PASS', output)


